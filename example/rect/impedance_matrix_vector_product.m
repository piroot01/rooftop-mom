%% impedance matrix vector product
%
%   Description:
%       This example compares four ways of applying the impedance matrix of a rectangular antenna (side ratio
%       1:2) to a random vector. The raw approach assembles the full (dense) impedance matrix and multiplies it,
%       which costs O(N^2) memory and time. The FFT and the split-FFT approaches store only the Toeplitz kernels
%       of the greens matrix and apply it in O(N log N): the FFT variant embeds the kernels into zero-padded
%       circulants, the split-FFT variants transform only arrays of the grid size using the subband spectra. The
%       fast split FFT shares transforms between the subbands (fewest operations), the memory efficient one
%       transforms each contribution alone in a single grid array (lowest peak memory).
%       The first summary table lists the mean application time, the speed-up and the relative error with respect
%       to the raw product. The second one lists the memory of the stored operator and the peak working memory of
%       one multiplication (output included) given by the applicators.

clc; clearvars; close all;

% Add required paths.
currentDir = fileparts(mfilename('fullpath'));
srcDir = fullfile(currentDir, '..', '..', 'src');
addpath(srcDir);

utilsDir = fullfile(currentDir, 'utils');
addpath(utilsDir);

loggerDir = fullfile(currentDir, '..', '..', '3rd', 'matlab-logger', 'src');
addpath(loggerDir);

% Configure the logger.
logger.Logger.configure( ...
    'timeFormat', 'ss.SSS', ...
    'minLevel', logger.LogLevel.DEBUG, ...
    'sinks', { ...
        logger.sink.ConsoleSink(), ...
    } ...
);

%% Prepare example inputs
% Electrical size of the antenna (with 10 rooftops per wavelength it gives 50x100 faces, i.e. 9850 rooftops).
electricalSize = 35;

% Constants used to compute the wavenumber and antenna size.
% Number of rooftops per wavelength to aim for.
rooftopCountPerOneWavelength = 10;

% Antenna side aspect ratio (sizeX:sizeY) will be 1:antennaSidesRatio.
antennaSidesRatio = 2;

% Order of the Gauss–Legendre quadrature.
quadratureOrder = 3;

% Memory allocation for a single chunk (number of elements, complex doubles).
chunkSize = 5e6;

% Number of the repeated applications used to measure the mean application time.
repetitionCount = 100;

%% Example body
[countX, countY, sizeX, sizeY] = generateAntennaDimensions(electricalSize, antennaSidesRatio, rooftopCountPerOneWavelength);

% Compute the wavenumber for the current antenna geometry.
wavenumber = 2 * electricalSize / sqrt(sizeX^2 * countX^2 + sizeY^2 * countY^2);

DEBUG('impedance_matrix_vector_product: Assembling the greens matrix kernels.');

solverContext = prepareSolverContext( ...
    'countX', countX, ...
    'countY', countY, ...
    'sizeX', sizeX, ...
    'sizeY', sizeY, ...
    'quadratureOrder', quadratureOrder, ...
    'wavenumber', wavenumber, ...
    'chunkSize', chunkSize ...
);

DEBUG('impedance_matrix_vector_product: Assembling the full impedance matrix.');

impedanceMatrix = generateImpedanceMatrix( ...
    'countX', countX, ...
    'countY', countY, ...
    'sizeX', sizeX, ...
    'sizeY', sizeY, ...
    'quadratureOrder', quadratureOrder, ...
    'wavenumber', wavenumber, ...
    'chunkSize', chunkSize ...
);

% Greens matrix applicators working with the kernels only.
fftApplicator = generateGreensMatrixApplicator(solverContext, ...
    'sizeX', sizeX, ...
    'sizeY', sizeY, ...
    'useSplitFFT', false ...
);

splitFFTApplicator = generateGreensMatrixApplicator(solverContext, ...
    'sizeX', sizeX, ...
    'sizeY', sizeY, ...
    'useSplitFFT', true ...
);

memoryEfficientApplicator = generateGreensMatrixApplicator(solverContext, ...
    'sizeX', sizeX, ...
    'sizeY', sizeY, ...
    'useSplitFFT', true, ...
    'memoryEfficient', true ...
);

%% Matrix-vector products
basisSize = fftApplicator.inputSize();
fprintf('Applying the impedance matrix of %dx%d faces (%d rooftops).\n', countX, countY, basisSize);

randomVector = randn(basisSize, 1) + 1i * randn(basisSize, 1);

[outputRaw, timeRaw] = measureApplicationTime(@() impedanceMatrix * randomVector, repetitionCount);
[outputFFT, timeFFT] = measureApplicationTime(@() fftApplicator.apply(randomVector), repetitionCount);
[outputSplitFFT, timeSplitFFT] = measureApplicationTime(@() splitFFTApplicator.apply(randomVector), repetitionCount);
[outputMemoryEfficient, timeMemoryEfficient] = measureApplicationTime(@() memoryEfficientApplicator.apply(randomVector), repetitionCount);

%% Memory of the multiplications
% Memory of the stored operators: the dense matrix versus the spectra of the kernels.
impedanceMatrixInfo = whos('impedanceMatrix');
storedMemory = [ ...
    impedanceMatrixInfo.bytes, ...
    fftApplicator.memory().bytes(), ...
    splitFFTApplicator.memory().bytes(), ...
    memoryEfficientApplicator.memory().bytes() ...
];

% Peak working memory of one multiplication, the dense product allocates just its output.
outputInfo = whos('outputRaw');
peakMemory = [ ...
    outputInfo.bytes, ...
    fftApplicator.workingMemory().bytes(), ...
    splitFFTApplicator.workingMemory().bytes(), ...
    memoryEfficientApplicator.workingMemory().bytes() ...
];

%% Summary tables
names = {'Raw', 'FFT', 'Split FFT', 'Split FFT (memory)'};
methods = { ...
    'Dense impedance matrix product', ...
    'Zero-padded circulant embedding', ...
    'Subbands sharing transforms', ...
    'One grid array per contribution' ...
};

printApplicationSummary(names, methods, ...
    [timeRaw, timeFFT, timeSplitFFT, timeMemoryEfficient], ...
    [ ...
        0, ...
        norm(outputFFT - outputRaw) / norm(outputRaw), ...
        norm(outputSplitFFT - outputRaw) / norm(outputRaw), ...
        norm(outputMemoryEfficient - outputRaw) / norm(outputRaw) ...
    ] ...
);

printMemorySummary(names, methods, storedMemory, peakMemory);

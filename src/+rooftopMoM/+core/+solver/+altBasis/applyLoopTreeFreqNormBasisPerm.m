function I = applyLoopTreeFreqNormBasisPerm(I, greensMatrixApplicator, loopTreeTrans, loopTreeData, omega)
% applyLoopTreeFreqNormBasisPerm: This function will apply all of the sandwitching matrices, it performs
%   the transition into the loop-tree basis, frequency normalization separately of the magnetic and electric part.
%   Finally it also does the basis rearangement method described in 5th capitol of Integral Equation Methods for
%   Electromagnetic and Elastic Waves from Wen Cho Chew and others.
%
%   Inputs:
%       I: Input Nx1 current; I = [L, Q], where L is the current associtaed with the loop basis and Q is the surface charge
%           tied to the tree basis
%       greensMatrixApplicator: Instance of any class that derives from the GreensMatrixApplicator. It basically implements
%           the fast application of the impedance matrix based on the rooftop basis.
%       loopTreeTrans: NxN sparse matrix that transforms the loop-tree currents into the rooftop ones.
%       loopTreeData: Struct that is generated by the generateLoopTreeToRooftopTransformation function.
%       omega: Angular speed of the incident wave, used for frequency normalization.
%
%   Output:
%       I: Output Nx1 current.

    % First we apply the K inverse on the tree part of the current.
    handle = @(x) rooftopMoM.core.solver.altBasis.utils.applyKInvMatrix(x, loopTreeData.tree);
    I = rooftopMoM.core.solver.altBasis.utils.applyToTreeCurrent(I, loopTreeData.loopCount, handle);

    % Secondly do the forward frequency normalization.
    I = rooftopMoM.core.solver.altBasis.utils.applyForwardFreqNorm(I, loopTreeData.loopCount, omega);

    % Next we apply the transition to rooftop basis.
    I = loopTreeTrans * I;

    % Apply the impedance matrix using the fast convolution.
    I = greensMatrixApplicator.apply(I);

    % To get back to the loop-tree basis, we use the fact that in the first part of the inner product
    % the current vector is just transposed, hence the matrix that maps the rooftop current bact to the
    % loop-tree current is a transpose of the loopTreeTrans.
    I = loopTreeTrans.' * I;

    % Perform the backward normalization.
    I = rooftopMoM.core.solver.altBasis.utils.applyBackwardFreqNorm(I, loopTreeData.loopCount, omega);

    % And lastly apply the K transpose inverse via the fast O(N) algorithm.
    handle = @(x) rooftopMoM.core.solver.altBasis.utils.applyKTransposeInvMatrix(x, loopTreeData.tree);
    I = rooftopMoM.core.solver.altBasis.utils.applyToTreeCurrent(I, loopTreeData.loopCount, handle);
end
